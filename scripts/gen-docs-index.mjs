#!/usr/bin/env node
// Builds docs/INDEX.md: every SPEC.md section, CLI guide (crates/brain-cli/guides), docs/*.md and docs/backend/*.md
// with its title and a one-line summary taken from its first paragraph. New files appear without editing this script.
//   node scripts/gen-docs-index.mjs          rewrite docs/INDEX.md
//   node scripts/gen-docs-index.mjs --check  exit 1 when docs/INDEX.md is stale or a docs/backend page is not linked
//                                           from docs/BACKEND.md
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const MAX = 160

const mdFiles = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
        .filter((e) => e.isFile() && e.name.endsWith('.md'))
        .map((e) => e.name)
        .sort()
    : []

const clean = (s) =>
  s
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<!--.*?-->/g, '')
    .replace(/\*\*/g, '')
    .replace(/\s+/g, ' ')
    .trim()

// One sentence of the first prose paragraph (no headings, code, tables, lists, quotes or planned blocks).
export function summary(lines) {
  let planned = false
  let fence = false
  const para = []
  let firstItem = ''
  for (const raw of lines) {
    const line = raw.trim()
    if (line.startsWith('```')) { fence = !fence; if (para.length) break; continue }
    if (fence) continue
    if (line.startsWith('<!--planned')) { planned = true; continue }
    if (line.startsWith('<!--/planned')) { planned = false; continue }
    if (planned) continue
    if (line === '') { if (para.length) break; continue }
    if (line.startsWith('#')) break // the next section: this one has no prose
    if (/^(#|\||- |\* |> |<|\d+\. )/.test(line)) {
      if (para.length) break
      if (!firstItem && /^(- |\* )/.test(line)) firstItem = line.slice(2)
      continue
    }
    // indented continuation of a list item, not a paragraph
    if (!para.length && /^\s/.test(raw)) continue
    para.push(line)
  }
  let text = clean(para.length ? para.join(' ') : firstItem)
  const end = text.search(/\.(\s|$)/)
  if (end > 0) text = text.slice(0, end + 1)
  if (text.length > MAX) text = text.slice(0, MAX - 1).trimEnd() + '…'
  return (text || '—').replace(/\|/g, '\\|')
}

const anchor = (heading) =>
  heading
    .toLowerCase()
    .replace(/[^a-z0-9 _-]/g, '')
    .trim()
    .replace(/ /g, '-')

function titleOf(src, fallback) {
  const h = src.split('\n').find((l) => /^# /.test(l))
  return h ? clean(h.slice(2)) : fallback
}

function bodyAfterTitle(src) {
  const lines = src.split('\n')
  const i = lines.findIndex((l) => /^# /.test(l))
  return lines.slice(i + 1)
}

export function buildIndex(root) {
  const out = [
    '<!-- generated by scripts/gen-docs-index.mjs; do not edit — run `node scripts/gen-docs-index.mjs` -->',
    '# Documentation index',
    '',
    'Every framework document with a one-line summary. Apps get their own generated docs with `brain docs`.',
    '',
  ]
  const table = (rows) => {
    out.push('| Document | Summary |', '|---|---|')
    for (const [link, text] of rows) out.push(`| ${link} | ${text} |`)
    out.push('')
  }

  const spec = readFileSync(join(root, 'SPEC.md'), 'utf8').split('\n')
  const sections = []
  let planned = false
  for (let i = 0; i < spec.length; i++) {
    const l = spec[i].trim()
    if (l.startsWith('<!--planned')) planned = true
    else if (l.startsWith('<!--/planned')) planned = false
    else if (!planned && /^## /.test(spec[i])) {
      const h = spec[i].slice(3).trim()
      sections.push([`[${clean(h).replace(/\|/g, '\\|')}](../SPEC.md#${anchor(h)})`, summary(spec.slice(i + 1))])
    }
  }
  out.push('## SPEC.md (the contract for app authors; `brain spec`)', '')
  table(sections)

  const guideDir = join(root, 'crates/brain-cli/guides')
  out.push('## CLI guides (`brain guide <topic>`)', '')
  table(
    mdFiles(guideDir).map((f) => {
      const first = readFileSync(join(guideDir, f), 'utf8').split('\n')[0]
      const topic = f.replace(/\.md$/, '')
      const what = first.includes(' — ') ? first.split(' — ').slice(1).join(' — ') : topic
      return [`[${topic}](../crates/brain-cli/guides/${f})`, clean(what).replace(/\|/g, '\\|')]
    }),
  )

  for (const [dir, heading, prefix] of [
    ['docs', '## docs/', ''],
    ['docs/backend', '## docs/backend/', 'backend/'],
  ]) {
    const files = mdFiles(join(root, dir)).filter((f) => f !== 'INDEX.md')
    if (!files.length) continue
    out.push(heading, '')
    table(
      files.map((f) => {
        const src = readFileSync(join(root, dir, f), 'utf8')
        return [`[${titleOf(src, f).replace(/\|/g, '\\|')}](${prefix}${f})`, summary(bodyAfterTitle(src))]
      }),
    )
  }
  return out.join('\n').trimEnd() + '\n'
}

// docs/backend/*.md pages that docs/BACKEND.md does not link.
export function unlinkedBackendPages(root) {
  const files = mdFiles(join(root, 'docs/backend'))
  if (!files.length) return []
  const hub = existsSync(join(root, 'docs/BACKEND.md')) ? readFileSync(join(root, 'docs/BACKEND.md'), 'utf8') : ''
  return files.filter((f) => !hub.includes(`backend/${f}`)).map((f) => `docs/backend/${f}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const want = buildIndex(root)
  const path = join(root, 'docs/INDEX.md')
  if (process.argv.includes('--check')) {
    const problems = []
    if ((existsSync(path) ? readFileSync(path, 'utf8') : '') !== want) problems.push('docs/INDEX.md is stale; fix: node scripts/gen-docs-index.mjs')
    for (const f of unlinkedBackendPages(root)) problems.push(`${f} is not linked from docs/BACKEND.md; fix: add a link to it there`)
    for (const p of problems) console.error(p)
    process.exit(problems.length ? 1 : 0)
  }
  writeFileSync(path, want)
  console.log('docs/INDEX.md written')
}
