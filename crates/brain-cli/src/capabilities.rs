//! The capability catalog: what an app author can use today, generated from the tables the compiler dispatches on, so
//! it cannot claim a feature that is gone or miss one that was added. `brain capabilities` prints it,
//! `docs/CAPABILITIES.md` is that output and a test fails when they differ. A release manifest's capability entries
//! are listed by version; an entry is only as true as its `uses`/`adopt` proof in the release tests.

use std::fmt::Write;

fn list(value: &serde_json::Value) -> String {
    value.as_array().map(|items| items.iter().filter_map(|i| i.as_str()).map(|i| format!("`{i}`")).collect::<Vec<_>>().join(" ")).unwrap_or_default()
}

/// Compact form for a scaffolded `AGENTS.md`: names only, the commands give the detail.
pub fn summary() -> String {
    let backend = brain_backend::capabilities::inventory();
    let field_types: Vec<String> = backend["fieldTypes"].as_array().into_iter().flatten().filter_map(|f| f["type"].as_str()).map(|t| format!("`{t}`")).collect();
    let recipes = crate::recipes::list();
    let recipe_names: Vec<String> = recipes["recipes"].as_array().into_iter().flatten().filter_map(|r| r["name"].as_str()).map(|n| format!("`{n}`")).collect();
    let kinds: Vec<String> = crate::scaffold::ADD_KINDS.iter().map(|(name, _)| format!("`{name}`")).collect();
    format!(
        "## Capabilities\nCheck here before building something by hand; `brain capabilities` prints the full catalog.\n- `brain add`: {}.\n- `brain recipe <name> --apply`: {}.\n- Backend field types: {}. Filters: {}. Policy grants: {}. Details: `brain backend capabilities`.\n- Topics: `brain guide`; helpers: `brain lib list`; reference pages: `brain guide docs`.\n",
        kinds.join(" "),
        recipe_names.join(" "),
        field_types.join(" "),
        list(&backend["filterOperators"]),
        list(&backend["policy"]["grants"]),
    )
}

pub fn render() -> Result<String, String> {
    let mut out = String::from("<!-- generated by `brain capabilities`; do not edit — run `brain capabilities > docs/CAPABILITIES.md` -->\n# Capabilities\n\nWhat an app author can use, generated from the tables the compiler dispatches on. `SPEC.md` is the contract for how each works.\n\n");
    out.push_str("## Playbooks (`brain guide <topic>`)\n\n| Topic | What it covers |\n|---|---|\n");
    for (topic, summary, _) in crate::guide::GUIDES {
        let _ = writeln!(out, "| `{topic}` | {summary} |");
    }
    out.push_str("\n## Generators (`brain add <kind>`)\n\n");
    let kinds: Vec<String> = crate::scaffold::ADD_KINDS.iter().map(|(name, _)| format!("`{name}`")).collect();
    let _ = writeln!(out, "{}", kinds.join(" "));
    out.push_str("\n## Recipes (`brain recipe <name>`, `--apply` writes the files)\n\n| Recipe | States it covers |\n|---|---|\n");
    let recipes = crate::recipes::list();
    for recipe in recipes["recipes"].as_array().into_iter().flatten() {
        let _ = writeln!(out, "| `{}` | {} |", recipe["name"].as_str().unwrap_or_default(), list(&recipe["states"]));
    }
    let backend = brain_backend::capabilities::inventory();
    out.push_str("\n## Native backend (`brain backend capabilities`)\n\n| Field type | Example | Filters | Sortable |\n|---|---|---|---|\n");
    for field in backend["fieldTypes"].as_array().into_iter().flatten() {
        let _ = writeln!(out, "| `{}` | `{}` | {} | {} |", field["type"].as_str().unwrap_or_default(), field["example"].as_str().unwrap_or_default().replace('|', "\\|"), list(&field["filters"]), if field["sortable"] == true { "yes" } else { "no" });
    }
    let _ = writeln!(out, "\nField options: {}.\n\nFilter operators: {}.\n\nPolicy operations: {}.\n\nPolicy grants: {}.", list(&backend["fieldOptions"]), list(&backend["filterOperators"]), list(&backend["policy"]["operations"]), list(&backend["policy"]["grants"]));
    out.push_str("\n## Added by release\n");
    for release in crate::releases::all()?.iter().rev() {
        let mut capabilities: Vec<_> = release.entries.iter().filter(|e| e.kind == crate::releases::Kind::Capability).collect();
        if capabilities.is_empty() {
            continue;
        }
        capabilities.sort_by(|a, b| a.id.cmp(&b.id));
        let _ = writeln!(out, "\n### {}\n", release.version);
        for entry in capabilities {
            let _ = writeln!(out, "- {}{}", entry.title, entry.guide.as_deref().map(|g| format!(" (`{g}`)")).unwrap_or_default());
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_committed_catalog_matches_the_tables() {
        let committed = std::fs::read_to_string(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/CAPABILITIES.md")).unwrap_or_default();
        assert!(committed == super::render().unwrap(), "docs/CAPABILITIES.md is stale; fix: run `brain capabilities > docs/CAPABILITIES.md`");
    }
    #[test]
    fn the_summary_names_real_entries() {
        let summary = super::summary();
        for name in ["`resource`", "`auth-ui`", "`owner`", "brain capabilities"] {
            assert!(summary.contains(name), "{name} missing from: {summary}");
        }
    }
    #[test]
    fn the_catalog_covers_every_table() {
        let text = super::render().unwrap();
        for (topic, _, _) in crate::guide::GUIDES {
            assert!(text.contains(&format!("| `{topic}` |")), "{topic}");
        }
        for (kind, _) in crate::scaffold::ADD_KINDS {
            assert!(text.contains(&format!("`{kind}`")), "{kind}");
        }
    }
}
